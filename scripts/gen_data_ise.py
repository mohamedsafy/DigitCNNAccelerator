"""Standalone generator for the ISE 14.7 project (numpy only, no Keras).

Writes:
  src/cnn_weights_pkg.vhd          weight/bias package (VHDL-93)
  sim/images.txt, golden_pred.txt, labels.txt   testbench vectors

Usage (from the ise_project folder):
  python scripts/gen_data_ise.py [N_IMAGES] [START_INDEX] [MNIST_DIR]
MNIST_DIR must contain t10k-images-idx3-ubyte.gz and t10k-labels-idx1-ubyte.gz
(only needed for the testbench vectors; the package is always written)."""
import os, sys, json, gzip
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")

def im2col(x, k=3):
    n, h, w, c = x.shape
    ho, wo = h - k + 1, w - k + 1
    return np.concatenate([x[:, i:i+ho, j:j+wo, :] for i in range(k) for j in range(k)], axis=-1)

def maxpool(x):
    n, h, w, c = x.shape
    h2, w2 = h // 2, w // 2
    return x[:, :2*h2, :2*w2, :].reshape(n, h2, 2, w2, 2, c).max(axis=(2, 4))

def golden(xq, P, W):   # identical to model/quantize.py golden()
    a = xq.astype(np.int64)[..., None]
    for L in ("conv1", "conv2"):
        acc = im2col(a) @ W[L+"_w"].reshape(-1, W[L+"_w"].shape[-1]).astype(np.int64) + W[L+"_b"]
        a = maxpool(np.clip(acc >> P[L]["shift"], 0, 255))
    logits = a.reshape(a.shape[0], -1) @ W["fc_w"].astype(np.int64) + W["fc_b"]
    return logits.argmax(1)

def mat(name, M):
    rows = ",\n    ".join("(" + ", ".join(str(int(v)) for v in r) + ")" for r in M)
    return f"  constant {name} : int2d(0 to {M.shape[0]-1}, 0 to {M.shape[1]-1}) := (\n    {rows});\n"

def vec(name, v):
    return f"  constant {name} : int1d(0 to {len(v)-1}) := (" + ", ".join(str(int(x)) for x in v) + ");\n"

if __name__ == "__main__":
    n     = int(sys.argv[1]) if len(sys.argv) > 1 else 20
    start = int(sys.argv[2]) if len(sys.argv) > 2 else 0
    mdir  = sys.argv[3] if len(sys.argv) > 3 else os.path.join(ROOT, "mnist")
    W = dict(np.load(os.path.join(HERE, "quant_weights.npz")))
    P = json.load(open(os.path.join(HERE, "quant_params.json")))
    m1, m2, m3 = W["conv1_w"].reshape(9, 8), W["conv2_w"].reshape(72, 16), W["fc_w"]
    pkg = ["-- AUTO-GENERATED by scripts/gen_data_ise.py from quant_weights.npz -- do not edit.\n",
           "-- INT8 weights (value = q / 2^fw) and INT32 biases at accumulator scale.\n",
           "-- Matrices are W[mw][mh]: row = input index (ki,kj,c order), column = output neuron.\n",
           "-- VHDL-93 compatible (ISE 14.7 / XST / ISim).\n",
           "package cnn_weights_pkg is\n",
           "  type int1d is array (natural range <>) of integer;\n",
           "  type int2d is array (natural range <>, natural range <>) of integer;\n",
           f"  constant SHIFT1 : natural := {P['conv1']['shift']};  -- requant shift after conv1\n",
           f"  constant SHIFT2 : natural := {P['conv2']['shift']};  -- requant shift after conv2\n",
           mat("W1", m1), vec("B1", W["conv1_b"]), mat("W2", m2), vec("B2", W["conv2_b"]),
           mat("W3", m3), vec("B3", W["fc_b"]),
           "  function wval(layer, mw, mh : natural) return integer;\n",
           "  function bval(layer, mh : natural) return integer;\n",
           "end package;\n\n",
           "package body cnn_weights_pkg is\n",
           "  function wval(layer, mw, mh : natural) return integer is\n  begin\n",
           "    case layer is\n      when 1 => return W1(mw, mh);\n      when 2 => return W2(mw, mh);\n",
           "      when others => return W3(mw, mh);\n    end case;\n  end function;\n",
           "  function bval(layer, mh : natural) return integer is\n  begin\n",
           "    case layer is\n      when 1 => return B1(mh);\n      when 2 => return B2(mh);\n",
           "      when others => return B3(mh);\n    end case;\n  end function;\n",
           "end package body;\n"]
    open(os.path.join(ROOT, "src", "cnn_weights_pkg.vhd"), "w", newline="\n").write("".join(pkg))
    print("wrote src/cnn_weights_pkg.vhd")

    img = os.path.join(mdir, "t10k-images-idx3-ubyte.gz")
    if not os.path.exists(img):
        print("MNIST not found in", mdir, "-> skipped testbench vectors"); sys.exit(0)
    with gzip.open(img) as f: x = np.frombuffer(f.read(), np.uint8, offset=16).reshape(-1, 28, 28)
    with gzip.open(os.path.join(mdir, "t10k-labels-idx1-ubyte.gz")) as f:
        y = np.frombuffer(f.read(), np.uint8, offset=8).astype(np.int64)
    x, y = x[start:start+n], y[start:start+n]
    sim = os.path.join(ROOT, "sim")
    np.savetxt(os.path.join(sim, "images.txt"), x.reshape(-1), fmt="%d")
    np.savetxt(os.path.join(sim, "golden_pred.txt"), golden(x, P, W), fmt="%d")
    np.savetxt(os.path.join(sim, "labels.txt"), y, fmt="%d")
    print(f"wrote sim/ vectors for {n} images (from index {start})")
